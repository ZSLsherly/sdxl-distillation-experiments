import os,re,json,hashlib
from pathlib import Path
import numpy as np
import torch
from PIL import Image
from transformers import CLIPModel,CLIPConfig,CLIPTokenizer,CLIPImageProcessor
out=Path.cwd(); modeldir=out.parent/'semantic_joint4_uniform_1024/model'
cases=json.loads((out/'cases.json').read_text())
ids=[r['index'] for r in cases];prompts=[r['prompt'] for r in cases]
import sys
arm=sys.argv[1]
torch.set_num_threads(2)
assert (modeldir/'revision.txt').read_text().strip()=='3d74acf9a28c67741b2f4f2ea7635f0aaf6f0268'
config=CLIPConfig.from_pretrained(modeldir,local_files_only=True)
model=CLIPModel(config).eval()
sd=torch.load(modeldir/'pytorch_model.bin',weights_only=True,map_location='cpu')
# Historical CLIP checkpoints save nonparameter position indices regenerated by transformers.
for k in ('vision_model.embeddings.position_ids','text_model.embeddings.position_ids'):
    if k not in model.state_dict() and k in sd: del sd[k]
model.load_state_dict(sd,strict=True);del sd
tok=CLIPTokenizer.from_pretrained(modeldir,local_files_only=True)
proc=CLIPImageProcessor.from_pretrained(modeldir,local_files_only=True)
def unit(t):return torch.nn.functional.normalize(t.float(),dim=-1).numpy()
@torch.inference_mode()
def texts(ss):
    parts=[]
    for j in range(0,len(ss),16):
        inp=tok(ss[j:j+16],padding=True,truncation=True,max_length=77,return_tensors='pt')
        v=model.text_projection(model.text_model(**inp).pooler_output)
        parts.append(unit(v))
    return np.concatenate(parts)

@torch.inference_mode()
def images(a):
 parts=[]
 for j in range(0,1024,8):
  folder=out/'reference'/a if j<128 else out/'images'/a
  ims=[]
  for i in ids[j:j+8]:
   with Image.open(folder/f'{i:05d}.png') as im:ims.append(im.convert('RGB'))
  x=proc(images=ims,return_tensors='pt')['pixel_values']
  parts.append(unit(model.visual_projection(model.vision_model(pixel_values=x).pooler_output)))
 return np.concatenate(parts)
folders={arm:out}
text_vec=texts(prompts)
# One fixed same-topic alternative per eligible caption; do not select cases by model output.
edits=[]
rules=[('count',r'\b(two|three)\b',{'two':'three','three':'two'}),
       ('color',r'\b(red|blue|green|yellow)\b',{'red':'blue','blue':'red','green':'yellow','yellow':'green'}),
       ('pose',r'\b(sitting|standing)\b',{'sitting':'standing','standing':'sitting'})]
for j,p in enumerate(prompts):
    for cat,rule,alts in rules:
        matches=list(re.finditer(rule,p,re.I))
        if len(matches)!=1:continue
        match=matches[0];alt=p[:match.start()]+alts[match[0].lower()]+p[match.end():]
        edits.append((j,cat,alt));break
alts=texts([e[2] for e in edits]) if edits else []
metrics={};per={}; details={}
for a,d in folders.items():
    im=images(a); sim=im@text_vec.T
    assert np.isfinite(sim).all()
    pos=sim.diagonal()*100
    # Exact duplicate captions count as equivalent for retrieval.
    rank=np.array([1+np.count_nonzero(sim[i]>max(sim[i,j] for j,t in enumerate(prompts) if t==p)) for i,p in enumerate(prompts)])
    per[a]=pos
    metrics[a]={'cosine_x100':float(pos.mean()),'top1_correct':int((rank==1).sum()),'top5_correct':int((rank<=5).sum())}
    for cat in ['count','color','pose']:
        margin=[float(pos[j]-100*(im[j]@alts[idx])) for idx,(j,k,_) in enumerate(edits) if k==cat]
        metrics[a][cat]={'n':len(margin),'original_preferred':sum(m>0 for m in margin),'mean_margin':float(np.mean(margin)) if margin else None}
    details[a]={'alignment':pos.tolist(),'rank':rank.tolist()}
    print(a,metrics[a],flush=True)

(out/(arm+'_results.json')).write_text(json.dumps({'revision':(modeldir/'revision.txt').read_text().strip(),'metrics':metrics,'cases':cases,'per_case':details,'n':1024},indent=2))
